import { NextResponse } from "next/server";
import { llmConfigured } from "@/lib/env";
import { logger, errorMessage } from "@/lib/logger";
import { resolveWidgetBusiness } from "@/lib/db/widget";
import { corsHeaders, originAllowed } from "@/lib/widget/origin";
import { widgetError, widgetIdSchema } from "@/lib/widget/schema";

/**
 * GET /api/widget/<widgetPublicId>/config
 *
 * The ONLY public endpoint that is not the message endpoint. It returns what the embeddable
 * widget needs to render itself before a visitor types anything, and nothing else:
 *
 *   { welcomeMessage, brandColor, assistantDisclosure, responseMode }
 *
 * It deliberately returns no business id, no slug, no allowed-origin list, no safety policy and
 * no secret: a widget id is public, so anything here is public. `responseMode` is the EFFECTIVE
 * mode this deployment would answer in right now (the same decision the message endpoint makes),
 * so a widget can label itself honestly instead of guessing.
 *
 * Status codes match the message endpoint exactly:
 *   200  allowed origin (or no Origin header: curl, server-side render)
 *   403  an Origin that is not on this business's allow-list
 *   404  unknown or malformed widget id
 */

export const dynamic = "force-dynamic";

const DEFAULT_CONFIG = {
  welcomeMessage: "Hi — I am the website assistant for this business. I answer only from information the business has approved.",
  brandColor: "#0f172a",
  assistantDisclosure:
    "You are chatting with an automated assistant, not a person. It answers only from information this business has approved. " +
    'Replies marked "demo mode" are composed deterministically from those approved facts and are not generated by a live AI model. ' +
    "It cannot book, confirm or price work.",
};

function fail(status: number, code: Parameters<typeof widgetError>[0], message: string): NextResponse {
  return NextResponse.json(widgetError(code, message), { status, headers: { "cache-control": "no-store" } });
}

function asString(value: unknown): string | null {
  return typeof value === "string" && value.trim().length > 0 ? value.trim() : null;
}

export async function OPTIONS(request: Request, ctx: { params: Promise<{ publicId: string }> }) {
  const { publicId } = await ctx.params;
  const parsed = widgetIdSchema.safeParse(publicId);
  if (!parsed.success) return new NextResponse(null, { status: 404 });
  const business = await resolveWidgetBusiness(parsed.data).catch(() => null);
  if (!business || !originAllowed(business, request)) return new NextResponse(null, { status: 403 });
  return new NextResponse(null, { status: 204, headers: corsHeaders(request.headers.get("origin"), "GET, OPTIONS") });
}

export async function GET(request: Request, ctx: { params: Promise<{ publicId: string }> }) {
  const { publicId: rawId } = await ctx.params;
  const logContext: Record<string, unknown> = { widgetIdPrefix: String(rawId).slice(0, 8) };

  try {
    const id = widgetIdSchema.safeParse(rawId);
    if (!id.success) return fail(404, "unknown_widget", "This chat widget is not available.");

    const business = await resolveWidgetBusiness(id.data);
    if (!business) return fail(404, "unknown_widget", "This chat widget is not available.");
    logContext.businessId = business.businessId;

    if (!originAllowed(business, request)) {
      logger.warn("widget config refused: origin not allowed", logContext);
      return fail(403, "origin_not_allowed", "This page is not allowed to use this chat widget.");
    }

    const config = business.widgetConfig ?? {};
    // The effective mode, decided the same way the message endpoint decides it. With no live
    // credentials (or DEMO_MODE=true) this is always "demo", and the widget must say so.
    const responseMode: "demo" | "live" =
      llmConfigured() && business.aiResponseMode !== "demo" ? "live" : "demo";

    const body = {
      welcomeMessage: asString(config.welcome_message) ?? DEFAULT_CONFIG.welcomeMessage,
      brandColor: asString(config.brand_color) ?? DEFAULT_CONFIG.brandColor,
      assistantDisclosure: asString(config.assistant_disclosure) ?? DEFAULT_CONFIG.assistantDisclosure,
      responseMode,
    };

    logger.info("widget.config.served", { ...logContext, responseMode });
    return NextResponse.json(body, {
      status: 200,
      headers: { "cache-control": "no-store", ...corsHeaders(request.headers.get("origin"), "GET, OPTIONS") },
    });
  } catch (err) {
    logger.error("widget config failed", { ...logContext, reason: errorMessage(err) });
    return fail(500, "temporarily_unavailable", "The assistant is unavailable right now. Please try again shortly.");
  }
}
