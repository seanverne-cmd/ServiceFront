import { NextResponse } from "next/server";
import { llmConfigured } from "@/lib/env";
import { logger, errorMessage } from "@/lib/logger";
import { clientKey, ipHash, userAgentFamily } from "@/lib/auth/request-guard";
import {
  appendExchange,
  deriveVisitorId,
  loadKnowledge,
  openConversation,
  resolveWidgetBusiness,
  sha256,
  withWidgetContext,
} from "@/lib/db/widget";
import { answerQuestion, type ComposedAnswer } from "@/lib/widget/engine";
import { composeLiveAnswer } from "@/lib/widget/llm";
import { corsHeaders, originAllowed } from "@/lib/widget/origin";
import { checkWidgetRateLimit } from "@/lib/widget/rate-limit";
import { widgetError, widgetIdSchema, widgetMessageBodySchema } from "@/lib/widget/schema";

/**
 * POST /api/widget/<widgetPublicId>/message
 *
 * Body:    { conversationId?: uuid, text: string }
 * Returns: { conversationId, reply, mode: "demo" | "live", sources: [...], ... }
 *
 * The business is resolved FROM THE URL ID ONLY, server-side. Nothing in the body can name a
 * tenant, a role or a mode.
 *
 * Honesty rule: with no LLM credentials (or DEMO_MODE=true) every reply is deterministic,
 * labelled "demo" and prefixed "[demo mode]" — it is never presented as a live AI answer.
 */

export const dynamic = "force-dynamic";

const SYNTHETIC_BATCH = "demo-2026-10";
const MAX_BODY_BYTES = 8 * 1024;

const DEMO_DISCLOSURE =
  "Demonstration mode: this reply was composed deterministically from this business's approved facts. It was not generated by a live AI model.";
const LIVE_DISCLOSURE =
  "Live mode: generated by the configured language model from this business's approved facts, then checked for ungrounded claims before being shown.";

function fail(
  status: number,
  code: Parameters<typeof widgetError>[0],
  message: string,
  extra?: Record<string, string>,
): NextResponse {
  return NextResponse.json(widgetError(code, message), {
    status,
    headers: { "cache-control": "no-store", ...(extra ?? {}) },
  });
}

export async function OPTIONS(request: Request, ctx: { params: Promise<{ publicId: string }> }) {
  const { publicId } = await ctx.params;
  const parsed = widgetIdSchema.safeParse(publicId);
  if (!parsed.success) return new NextResponse(null, { status: 404 });
  const business = await resolveWidgetBusiness(parsed.data).catch(() => null);
  if (!business || !originAllowed(business, request)) return new NextResponse(null, { status: 403 });
  return new NextResponse(null, { status: 204, headers: corsHeaders(request.headers.get("origin")) });
}

export async function POST(request: Request, ctx: { params: Promise<{ publicId: string }> }) {
  const { publicId: rawId } = await ctx.params;
  const logContext: Record<string, unknown> = { widgetIdPrefix: String(rawId).slice(0, 8) };

  try {
    const id = widgetIdSchema.safeParse(rawId);
    if (!id.success) return fail(404, "unknown_widget", "This chat widget is not available.");

    // 1. Server-side tenant derivation. The client never sends a business id.
    const business = await resolveWidgetBusiness(id.data);
    if (!business) return fail(404, "unknown_widget", "This chat widget is not available.");
    logContext.businessId = business.businessId;

    // 2. Embed allow-list.
    if (!originAllowed(business, request)) {
      logger.warn("widget request refused: origin not allowed", logContext);
      return fail(403, "origin_not_allowed", "This page is not allowed to use this chat widget.");
    }
    const cors = corsHeaders(request.headers.get("origin"));

    // 3. Boundary validation.
    const declaredLength = Number(request.headers.get("content-length") ?? "0");
    if (Number.isFinite(declaredLength) && declaredLength > MAX_BODY_BYTES) {
      return fail(413, "invalid_request", "That message is too large.");
    }
    let rawBody: unknown;
    try {
      rawBody = await request.json();
    } catch {
      return fail(400, "invalid_request", "The request body must be JSON.");
    }
    const body = widgetMessageBodySchema.safeParse(rawBody);
    if (!body.success) {
      return fail(400, "invalid_request", "Messages must be text between 1 and 1000 characters, with no control characters.");
    }

    const visitorId = deriveVisitorId(clientKey(request), id.data);
    const rateKey = body.data.conversationId ?? visitorId;

    // 4. Rate limits, before any database or model work.
    const rate = checkWidgetRateLimit(clientKey(request), rateKey);
    if (!rate.allowed) {
      logger.warn("widget rate limited", { ...logContext, scope: rate.scope });
      return fail(429, "rate_limited", "Too many messages in a short time. Please wait a moment and try again.", {
        "retry-after": String(rate.retryAfter),
      });
    }

    // 5. Open the thread and load this business's approved facts (RLS-scoped).
    const isSynthetic = business.isSynthetic;
    const { knowledge, conversationId } = await withWidgetContext(business.businessId, async (tx) => {
      const conversationId = await openConversation(tx, {
        businessId: business.businessId,
        conversationId: body.data.conversationId,
        visitorId,
        pageUrl: null,
        referrer: null,
        userAgentFamily: userAgentFamily(request),
        visitorIpHash: ipHash(request),
        isSynthetic,
        syntheticBatch: isSynthetic ? SYNTHETIC_BATCH : null,
      });
      const knowledge = await loadKnowledge(tx, business.businessId);
      return { knowledge, conversationId };
    });

    if (!conversationId) return fail(404, "unknown_conversation", "That conversation is not available.");
    logContext.conversationId = conversationId;
    if (!knowledge) return fail(500, "temporarily_unavailable", "The assistant is unavailable right now.");

    // 6. Compose. Deterministic first — it is also the fallback if a live model misbehaves.
    const deterministic: ComposedAnswer = answerQuestion(knowledge, body.data.text);

    let reply = deterministic.reply;
    let mode: "demo" | "live" = "demo";
    let modelName: string | null = null;
    let modelProvider: string | null = null;
    let latencyMs: number | null = null;
    let fallbackReason: string | null = null;

    if (llmConfigured() && business.aiResponseMode !== "demo") {
      const live = await composeLiveAnswer(knowledge, body.data.text, deterministic);
      if (live.ok) {
        reply = live.reply;
        mode = "live";
        modelName = live.model;
        modelProvider = live.provider;
        latencyMs = live.latencyMs;
      } else {
        fallbackReason = live.reason;
      }
    }

    const labelledReply = mode === "demo" ? `[demo mode] ${reply}` : reply;

    // 7. Persist the exchange, then credit the conversation.
    await withWidgetContext(business.businessId, async (tx) => {
      await appendExchange(tx, {
        businessId: business.businessId,
        conversationId,
        visitorText: body.data.text,
        replyText: labelledReply,
        mode,
        answeredFromKnowledge: deterministic.grounded,
        factRefs: deterministic.factRefs,
        confidence: deterministic.confidence,
        intent: deterministic.intent,
        modelProvider,
        modelName,
        latencyMs,
        isSynthetic,
        syntheticBatch: isSynthetic ? SYNTHETIC_BATCH : null,
      });
    });

    // 8. Structured log WITHOUT the visitor's text or the reply: length + hash only.
    logger.info("widget.message.answered", {
      ...logContext,
      mode,
      intent: deterministic.intent,
      grounded: deterministic.grounded,
      textLength: body.data.text.length,
      textSha256Prefix: sha256(body.data.text).slice(0, 16),
      fallbackReason,
    });

    return NextResponse.json(
      {
        conversationId,
        reply: labelledReply,
        mode,
        modeLabel: mode === "demo" ? "demo mode (deterministic)" : `live model (${modelName})`,
        disclosure: mode === "demo" ? DEMO_DISCLOSURE : LIVE_DISCLOSURE,
        sources: deterministic.sources,
        intent: deterministic.intent,
        answeredFromKnowledge: deterministic.grounded,
        synthetic: isSynthetic,
        ...(fallbackReason ? { liveFallbackReason: fallbackReason } : {}),
      },
      { status: 200, headers: { "cache-control": "no-store", ...cors } },
    );
  } catch (err) {
    logger.error("widget message failed", { ...logContext, reason: errorMessage(err) });
    return fail(500, "temporarily_unavailable", "The assistant is unavailable right now. Please try again shortly.");
  }
}
