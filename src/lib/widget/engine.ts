function pickService(kb: KnowledgeBase, text: string): ServiceRow | null {
  const asked = tokens(text);
  let best: { row: ServiceRow; score: number } | null = null;
  for (const row of kb.services) {
    const own = tokens(`${row.slug.replace(/-/g, " ")} ${row.name} ${row.category ?? ""}`);
    const score = own.filter((t) => asked.includes(t)).length;
    if (score > 0 && (!best || score > best.score)) best = { row, score };
  }
  return best?.row ?? null;
}

function pickFaq(kb: KnowledgeBase, text: string): FaqRow | null {
  const asked = new Set(tokens(text));
  if (asked.size === 0) return null;
  let best: { row: FaqRow; score: number } | null = null;
  for (const row of kb.faqs) {
    const own = tokens(`${row.question} ${row.category ?? ""}`);
    const score = own.filter((t) => asked.has(t)).length;
    if (score > 0 && (!best || score > best.score)) best = { row, score };
  }
  // Two shared meaningful words is the bar; one is too loose to be called an answer.
  return best && best.score >= 2 ? best.row : null;
}

function faqFor(kb: KnowledgeBase, category: string): FaqRow | null {
  return kb.faqs.find((f) => f.category === category) ?? null;
}

function areaSource(area: AreaRow): AnswerSource {
  return { type: "service_area", id: area.id, label: `service area: ${area.name}${area.region ? `, ${area.region}` : ""}` };
}

function faqSource(faq: FaqRow): AnswerSource {
  return { type: "faq", id: faq.id, label: `FAQ: ${faq.question}` };
}

function serviceSource(row: ServiceRow): AnswerSource {
  return { type: "service", id: row.id, label: `service: ${row.name}` };
}

function verifiedEmergencyPhone(kb: KnowledgeBase): string | null {
  return kb.business.emergencyPhoneVerified ? kb.business.emergencyPhone : null;
}

function contactLine(kb: KnowledgeBase): string {
  const phone = kb.business.primaryPhone;
  return phone ? `call ${kb.business.name} on ${phone}` : "contact the team by phone or email";
}

function addressLine(kb: KnowledgeBase): string | null {
  const b = kb.business;
  if (!b.addressLine1) return null;
  const parts = [b.addressLine1, b.addressLine2, [b.city, b.region].filter(Boolean).join(", "), b.postalCode].filter(Boolean);
  return parts.join(", ");
}

/** The safety guidance attached to a plumbing emergency. Restates the business's own note. */
function plumbingSafetyGuidance(kb: KnowledgeBase, text: string): string[] {
  const lines: string[] = [];
  if (matches(text, ["gas", "gas leak", "smell of gas", "smells like gas", "smell gas"])) {
    lines.push(
      "Suspected gas leak: leave the property first and do not use switches, flames or anything that could spark.",
    );
    lines.push("The approved note says to call the gas emergency line before anything else — this business's approved information names SoCalGas on 1-800-427-2200.");
  } else if (matches(text, ["sewage", "sewer", "toilet", "backing up", "backup"])) {
    lines.push("Stop using water fixtures in the property while the backup is happening, and keep children and pets away from the spill.");
  } else {
    lines.push("If water is escaping, turn the water off at the nearest isolation valve — usually under the sink, behind the cistern, or where the supply enters the property — if it is safe to reach.");
    lines.push("Keep clear of any electrical fittings or sockets that are wet, and do not use them.");
  }
  return lines;
}

function composeEmergency(kb: KnowledgeBase, text: string): ComposedAnswer {
  const phone = verifiedEmergencyPhone(kb);
  const sources: AnswerSource[] = [];

  if (kb.business.industry === "veterinary") {
    const emergencyFaq = faqFor(kb, "emergency");
    if (emergencyFaq) sources.push(faqSource(emergencyFaq));
    const hospital = phone
      ? `${kb.business.name} has confirmed this contact for emergencies: ${phone}.`
      : `${kb.business.name} has not published a verified emergency contact here, so please call the clinic directly.`;
    const reply = [
      `${kb.business.name} does not provide emergency or after-hours triage, and I am not able to assess how urgent this is or give any medication advice.`,
      hospital,
      "If your pet needs to be seen urgently, call that number now or take your pet to the nearest veterinary emergency hospital.",
      "I have not booked anything and I cannot arrange for a veterinarian to call you back; only clinic staff or the emergency hospital can do that.",
    ].join(" ");
    if (kb.business.emergencyInstructions) sources.push({ type: "policy", id: kb.business.id, label: "verified emergency instructions" });
    return { intent: "emergency", reply, sources, grounded: true, confidence: 0.9, factRefs: sources.map((s) => `${s.type}:${s.id}`) };
  }

  const guidance = plumbingSafetyGuidance(kb, text);
  const emergencyFaq = faqFor(kb, "emergency");
  if (emergencyFaq) sources.push(faqSource(emergencyFaq));
  const reply = [
    "Safety first.",
    ...guidance,
    phone
      ? `The verified emergency contact for ${kb.business.name} is ${phone}.`
      : `I do not have a verified emergency contact for ${kb.business.name} here — call the office on ${kb.business.primaryPhone ?? "their published number"}.`,
    kb.business.emergencyInstructions ? `Approved emergency note: ${kb.business.emergencyInstructions}` : "",
    "To be clear about what I cannot do: I have not dispatched anyone, no technician is on the way, and I cannot promise how quickly someone can attend. A dispatcher confirms that by phone.",
  ]
    .filter(Boolean)
    .join(" ");
  return { intent: "emergency", reply, sources, grounded: true, confidence: 0.9, factRefs: sources.map((s) => `${s.type}:${s.id}`) };
}

function composePricing(kb: KnowledgeBase, text: string): ComposedAnswer {
  const service = pickService(kb, text);
  const sources: AnswerSource[] = [];
  if (service) sources.push(serviceSource(service));
  if (service && service.priceNote) {
    return {
      intent: "pricing",
      reply: `${service.name}: the pricing note ${kb.business.name} has approved says "${service.priceNote}". That is the only pricing I can give you — anything else is confirmed by the team.`,
      sources,
      grounded: true,
      confidence: 0.85,
      factRefs: sources.map((s) => `service:${s.id}`),
    };
  }
  const reply = [
    service
      ? `I do not have an approved price for ${service.name}, and I will not invent one.`
      : "I do not have any approved pricing for that, and I will not invent a figure.",
    `${kb.business.name} gives prices and quotes directly — ${contactLine(kb)}.`,
    "If you would prefer, leave your name and a callback number and a team member will get back to you with pricing.",
  ].join(" ");
  return { intent: "pricing", reply, sources, grounded: false, confidence: 0.8, factRefs: [] };
}

function composeServiceArea(kb: KnowledgeBase, text: string): ComposedAnswer {
  const known = kb.areas.filter((a) => {
    const candidates = [a.name, a.city ?? ""].filter(Boolean).map(norm);
    return candidates.some((c) => c.length >= 3 && text.includes(c));
  });
  const zipArea = postalLookup(kb.areas, text);

  if (known.length > 0 || zipArea) {
    const area = known[0] ?? zipArea!;
    const others = kb.areas.filter((a) => a.id !== area.id).map((a) => a.name);
    const sources: AnswerSource[] = [areaSource(area), ...(others.length ? [{ type: "service_area_list", id: kb.business.id, label: `service area list (${kb.areas.length} areas)` }] : [])];
    const reply = [
      `Yes — ${area.name} is one of ${kb.business.name}'s service areas${area.isPrimary ? " (it is the primary service area)" : ""}.`,
      others.length ? `The other areas on the approved list are ${others.join(", ")}.` : "",
      area.travelNote ?? "",
      "If your address is at the edge of those areas, the team confirms whether they can get to you.",
    ]
      .filter(Boolean)
      .join(" ");
    return { intent: "service_area", reply, sources, grounded: true, confidence: 0.92, factRefs: sources.map((s) => `${s.type}:${s.id}`) };
  }

  const asked = text.match(/(?:service|serve|cover|work in|come to|travel to|near)\s+(?:the\s+)?([a-z][a-z' ]{1,28}?)(?:[?.!,]|$)/);
  const place = asked?.[1]
    ?.split(" ")
    .filter((w) => !["area", "my", "our", "your", "zip", "postal", "code"].includes(w))
    .join(" ")
    .trim();
  const reply = [
    place
      ? `I do not have "${place}" confirmed as one of ${kb.business.name}'s service areas, so I cannot say whether they cover it.`
      : `I cannot confirm that against ${kb.business.name}'s approved service area list, so I am not going to guess.`,
    `The team can confirm it: ${contactLine(kb)}.`,
    "If you leave your name, a callback number and the address, someone will call you back.",
  ].join(" ");
  return { intent: "service_area", reply, sources: [], grounded: false, confidence: 0.6, factRefs: [] };
}

function composeHours(kb: KnowledgeBase, text: string, now: Date): ComposedAnswer {
  if (kb.hours.length === 0) {
    return {
      intent: "hours",
      reply: `I do not have confirmed opening hours for ${kb.business.name}, so I will not guess. ${contactLine(kb)} to check.`,
      sources: [],
      grounded: false,
      confidence: 0.5,
      factRefs: [],
    };
  }
  const sources: AnswerSource[] = [{ type: "business_hours", id: kb.business.id, label: `business hours (${kb.hours.length} windows, ${kb.business.timezone})` }];
  const open = isOpenNow(kb.hours, kb.business.timezone, now);
  const afterHours = !open;
  const emergencyFaq = faqFor(kb, "emergency");
  const appointmentFaq = faqFor(kb, "appointments");

  const lines = [
    `${kb.business.name}'s approved opening hours (${kb.business.timezone}):`,
    ...describeHours(kb.hours).map((l) => `• ${l}`),
    `As of ${localTimeLabel(now, kb.business.timezone)} the business is ${open ? "inside" : "outside"} those opening hours.`,
  ];

  if (afterHours && emergencyFaq) {
    lines.push(emergencyFaq.answer);
    sources.push(faqSource(emergencyFaq));
  }
  if (matches(text, APPOINTMENT_ASK)) {
    if (appointmentFaq) {
      lines.push(appointmentFaq.answer);
      sources.push(faqSource(appointmentFaq));
    }
    lines.push("I cannot confirm or book a visit, and I cannot tell you what slots are available.");
  }
  return {
    intent: matches(text, APPOINTMENT_ASK) ? "appointment" : "hours",
    reply: lines.join(" "),
    sources,
    grounded: true,
    confidence: 0.9,
    factRefs: sources.map((s) => `${s.type}:${s.id}`),
  };
}

function composeContact(kb: KnowledgeBase): ComposedAnswer {
  const sources: AnswerSource[] = [{ type: "business_profile", id: kb.business.id, label: "business contact details" }];
  const address = addressLine(kb);
  const phone = verifiedEmergencyPhone(kb);
  const reply = [
    address ? `${kb.business.name} is at ${address}.` : `${kb.business.name} has not published a street address in the approved information.`,
    kb.business.primaryPhone ? `Main phone: ${kb.business.primaryPhone}.` : "",
    kb.business.primaryEmail ? `Email: ${kb.business.primaryEmail}.` : "",
    phone ? `Verified 24/7 emergency line: ${phone}.` : "",
  ]
    .filter(Boolean)
    .join(" ");
  return { intent: "contact", reply, sources, grounded: true, confidence: 0.9, factRefs: sources.map((s) => `${s.type}:${s.id}`) };
}

/**
 * Appointment intent. A visitor asking for a visit almost always names the job ("can someone
 * come tomorrow about my water heater"), so the reply must first confirm whether that job is
 * one of the business's approved services — from the stored service rows only — and only then
 * hand off. It never states or implies a slot, a time or availability: the business confirms
 * that, not this assistant.
 */
function composeAppointment(kb: KnowledgeBase, text: string): ComposedAnswer {
  const service = pickService(kb, text);
  const faq = faqFor(kb, "appointments");
  const sources: AnswerSource[] = [];
  const lines: string[] = [];

  if (service) {
    sources.push(serviceSource(service));
    lines.push(`Yes — ${service.name} is on ${kb.business.name}'s approved list of services.`);
    if (service.description) lines.push(service.description);
  }

  if (faq) {
    sources.push(faqSource(faq));
    lines.push(faq.answer);
  } else {
    lines.push(`I cannot book or confirm an appointment myself.`);
  }

  lines.push(
    "To be clear about what this chat can and cannot do: nothing has been booked, no slot or arrival time is reserved, and I cannot confirm when someone could attend. Only the team can confirm availability.",
  );
  lines.push(
    `To get it moving, ${contactLine(kb)} and a team member will arrange it. If you would rather be called back, leave your name, a callback number, the service address and the best time to reach you.`,
  );

  return {
    intent: "appointment",
    reply: lines.join(" "),
    sources,
    grounded: Boolean(service ?? faq),
    confidence: service ? 0.85 : 0.8,
    factRefs: sources.map((s) => `${s.type}:${s.id}`),
  };
}

function composeService(kb: KnowledgeBase, service: ServiceRow): ComposedAnswer {
  const sources = [serviceSource(service)];
  const reply = [
    `Yes — ${service.name} is on ${kb.business.name}'s approved list of services.`,
    service.description ? `${service.description}` : "",
    "Whether it fits your particular job, and when it could be done, is confirmed by the team — I cannot confirm availability or timing.",
  ]
    .filter(Boolean)
    .join(" ");
  return { intent: "service", reply, sources, grounded: true, confidence: 0.85, factRefs: sources.map((s) => `service:${s.id}`) };
}

function composeUnknown(kb: KnowledgeBase): ComposedAnswer {
  return {
    intent: "unknown",
    reply: [
      `I do not have that confirmed for ${kb.business.name}, and I will not guess at it.`,
      `The team can answer it directly: ${contactLine(kb)}.`,
      "If you would rather be called, tell me your name and a callback number and the team will follow up.",
    ].join(" "),
    sources: [],
    grounded: false,
    confidence: 0.5,
    factRefs: [],
  };
}

function composeGreeting(kb: KnowledgeBase): ComposedAnswer {
  return {
    intent: "greeting",
    reply: `Hello — this is the automated website assistant for ${kb.business.name}. I can help with opening hours, service areas, the services on their approved list, appointments and callbacks, and emergencies. What do you need?`,
    sources: [],
    grounded: false,
    confidence: 0.4,
    factRefs: [],
  };
}

/**
 * Route the message and compose the answer.
 *
 * Order matters: a safety-critical reading wins over a commercial one, so "our pipe burst,
 * how much will it cost?" gets safety guidance, not a price.
 */
export function answerQuestion(kb: KnowledgeBase, message: string, now: Date = new Date()): ComposedAnswer {
  const text = norm(message);
  const isVet = kb.business.industry === "veterinary";

  const emergency = isVet ? matches(text, EMERGENCY_VET) : matches(text, EMERGENCY_PLUMBING);
  if (emergency) return composeEmergency(kb, text);

  // A clinical question about an animal is never answered from a general knowledge base.
  if (isVet && matches(text, MEDICAL_LIMIT_ASK) && !matches(text, ["hours", "appointment", "book"])) {
    const faq = kb.faqs.find((f) => f.category === "limits") ?? null;
    if (faq) {
      return {
        intent: "unknown",
        reply: [
          faq.answer,
          "What I can do is share clinic information and pass a message to the veterinary team.",
        ].join(" "),
        sources: [faqSource(faq)],
        grounded: true,
        confidence: 0.8,
        factRefs: [`faq:${faq.id}`],
      };
    }
  }

  if (matches(text, PRICE_ASK)) return composePricing(kb, text);

  const areaFaq = faqFor(kb, "service-area");
  const areaKnown = kb.areas.some((a) => {
    const candidates = [a.name, a.city ?? ""].filter(Boolean).map(norm);
    return candidates.some((c) => c.length >= 3 && text.includes(c));
  });
  if ((matches(text, AREA_ASK) && !areaKnown) || areaKnown || postalLookup(kb.areas, text)) {
    return composeServiceArea(kb, text);
  }

  if (matches(text, HOURS_ASK)) return composeHours(kb, text, now);

  if (matches(text, APPOINTMENT_ASK)) return composeAppointment(kb, text);

  if (matches(text, CONTACT_ASK)) return composeContact(kb);

  const service = pickService(kb, text);
  if (service) return composeService(kb, service);

  const faq = pickFaq(kb, text);
  if (faq) {
    const sources = [faqSource(faq)];
    return {
      intent: "faq",
      reply: faq.answer,
      sources,
      grounded: true,
      confidence: 0.75,
      factRefs: [`faq:${faq.id}`],
    };
  }

  if (matches(text, GREETING_ASK) && text.split(" ").length <= 6) return composeGreeting(kb);

  // The service-area FAQ is the last honest fallback: it states the business's own areas.
  if (areaFaq && matches(text, ["outside", "around", "my city", "my town"])) {
    return { intent: "service_area", reply: areaFaq.answer, sources: [faqSource(areaFaq)], grounded: true, confidence: 0.7, factRefs: [`faq:${areaFaq.id}`] };
  }

  return composeUnknown(kb);
}

