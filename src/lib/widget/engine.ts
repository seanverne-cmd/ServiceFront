/**
 * ============================================================================
 *  The answering engine (deterministic, "demo mode")
 * ============================================================================
 * The visitor's text is an UNTRUSTED string. It is never used as an instruction: it is
 * matched against a fixed set of intents, each of which has a composition routine that can
 * only restate values from the business's own approved facts (KnowledgeBase).
 *
 * What this buys, and why it is not a prompt:
 *   - there is no place in this file where the visitor's text is interpolated into a reply;
 *   - no number, price, availability claim or policy can be produced unless a stored fact
 *     contains it (the only visitor-derived values echoed back are place names the business
 *     itself lists, and a service name the business itself publishes);
 *   - when nothing matches, the answer says plainly that it is not confirmed and offers a
 *     callback, instead of guessing.
 *
 * Every reply produced here is DEMONSTRATION MODE output: composed deterministically from
 * stored facts, never generated by a language model. The route adds the mode label.
 */

export type ChatIntent =
  | "greeting"
  | "emergency"
  | "pricing"
  | "service_area"
  | "hours"
  | "contact"
  | "appointment"
  | "service"
  | "faq"
  | "unknown";

export type AnswerSource = { type: string; id: string; label: string };

export type ComposedAnswer = {
  intent: ChatIntent;
  reply: string;
  sources: AnswerSource[];
  /** True only when the reply restates stored facts. False = "not confirmed". */
  grounded: boolean;
  confidence: number;
  factRefs: string[];
};

const STOPWORDS = new Set([
  "the", "and", "you", "your", "are", "for", "with", "can", "does", "did", "have", "has", "was",
  "what", "when", "where", "how", "why", "who", "our", "this", "that", "there", "here", "from",
  "about", "into", "please", "hello", "help", "need", "want", "get", "got", "any", "all", "not",
  "but", "they", "them", "his", "her", "its", "will", "would", "should", "could", "much", "many",
  "service", "services", "offer", "provide", "available", "availability", "work", "works", "day",
  "today", "tonight", "right", "now", "out", "under", "over", "just", "like", "than", "then",
]);

function norm(text: string): string {
  return text.toLowerCase().replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, " ").trim();
}

function tokens(text: string): string[] {
  return norm(text)
    .split(/[^a-z0-9']+/)
    .filter((t) => t.length >= 3 && !STOPWORDS.has(t));
}

/**
 * Phrase match on WHOLE WORDS.
 *
 * This used to be `text.includes(pattern)`, which is a substring test: "come to" matched inside
 * "someone come tomorrow", so "My water heater stopped working. Can someone come tomorrow?"
 * was routed to service_area and answered with a coverage refusal. Every pattern here is a
 * phrase in English, so it must match as a phrase: bounded on the left by the start of the
 * string or a non-word character, and on the right by the end or a non-word character.
 * A non-alphabetic pattern ("$") keeps the plain substring test, because "boundary + $" +
 * "boundary" would fail on "$500".
 */
function matches(text: string, patterns: Array<string | RegExp>): boolean {
  return patterns.some((p) => {
    if (typeof p !== "string") return p.test(text);
    const phrase = p.trim().toLowerCase();
    if (!/[a-z]/.test(phrase)) return text.includes(phrase);
    const escaped = phrase.replace(/[-/\\^$*+?.()|[\]{}]/g, (c) => "\\" + c);
    return new RegExp(`(?:^|[^a-z0-9])${escaped}(?![a-z0-9])`).test(text);
  });
}

