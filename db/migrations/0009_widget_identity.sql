-- 0009_widget_identity.sql
-- ServiceFront Phase 2a: the public widget identity, the widget's configuration, and the
-- narrow, anonymous row-level-security path the chat engine needs.
--
-- THREAT MODEL
--   The widget public id is printed in the customer's page source, so it must be treated as
--   public. It is therefore NOT a credential:
--     * it grants no administrative access: everything it can reach is filtered by the RLS
--       policies added below to exactly one business, and only for conversations/messages plus
--       the read-only knowledge base (services, service areas, FAQs, hours, contact details);
--     * it cannot name a business: the business_id for a request is derived server-side by
--       app.resolve_widget_business(widget_public_id) and is never read from the request body;
--     * a widget session sets app.current_user_id to the nil UUID, so every membership-based
--       policy (can_write_tenant / is_business_owner / can_access_tenant) evaluates to false
--       and the ordinary tenant write path stays closed to it.

-- ---------------------------------------------------------------------------
-- 1. Widget identity and configuration on the tenant row
-- ---------------------------------------------------------------------------
alter table public.businesses add column widget_public_id text;
alter table public.businesses
  add column widget_allowed_origins text[] not null default '{}'::text[];
alter table public.businesses add column widget_config jsonb not null default '{}'::jsonb;

-- Backfill: opaque, non-guessable, and stable for the lifetime of the business.
update public.businesses
   set widget_public_id = 'sfw_' || lower(substr(replace(gen_random_uuid()::text, '-', ''), 1, 24));

-- Per-business widget config. The disclosure text is mandatory and names the response mode
-- honestly, so a visitor is never told a deterministic reply came from a live AI model.
