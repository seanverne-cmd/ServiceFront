alter table public.businesses alter column widget_public_id set not null;
alter table public.businesses alter column widget_public_id
  set default ('sfw_' || lower(substr(replace(gen_random_uuid()::text, '-', ''), 1, 24)));

alter table public.businesses
  add constraint businesses_widget_public_id_key unique (widget_public_id);
alter table public.businesses
  add constraint businesses_widget_public_id_format
  check (widget_public_id ~ '^sfw_[a-z0-9]{16,40}$');
alter table public.businesses
  add constraint businesses_widget_config_object check (jsonb_typeof(widget_config) = 'object');
alter table public.businesses
  add constraint businesses_widget_origins_count check (cardinality(widget_allowed_origins) <= 20);

-- ---------------------------------------------------------------------------
-- 2. Widget session helpers (read only the session settings; no data access of their own)
-- ---------------------------------------------------------------------------
-- Set by withWidgetTransaction() for the duration of ONE transaction and to nothing else.
create or replace function app.widget_business_id()
returns uuid
language sql
stable
as $$
  select nullif(current_setting('app.widget_business_id', true), '')::uuid
$$;

create or replace function app.is_widget_session(p_business_id uuid)
returns boolean
language sql
stable
as $$
  select p_business_id is not null and p_business_id = app.widget_business_id()
$$;

-- ---------------------------------------------------------------------------
-- 3. Widget bootstrap: public id -> business (server-side derivation of business_id)
-- ---------------------------------------------------------------------------
-- The 0007 version took `p_public_key`; Postgres cannot rename an input parameter in place.
drop function if exists app.resolve_widget_business(text);

create or replace function app.resolve_widget_business(p_widget_public_id text)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_catalog
as $$
  select jsonb_build_object(
    'business_id', b.id,
    'slug', b.slug,
    'name', b.name,
    'industry', b.industry::text,
    'timezone', b.timezone,
    'ai_response_mode', b.ai_response_mode,
    'ai_safety_policy', b.ai_safety_policy,
    'widget_config', b.widget_config,
    'widget_allowed_origins', to_jsonb(b.widget_allowed_origins),
    'is_synthetic', b.is_synthetic
  )
  from public.businesses b
  where b.widget_public_id = nullif(trim(p_widget_public_id), '')
  limit 1
$$;

-- ---------------------------------------------------------------------------
-- 4. RLS for the anonymous widget session
--    Additive policies: they only ever match when app.widget_business_id is set (by the
--    server) AND equals the row's business_id. No writes outside conversations/messages.
-- ---------------------------------------------------------------------------
create policy businesses_select_widget on public.businesses for select
  using (app.is_widget_session(id));

create policy services_select_widget on public.services for select
  using (app.is_widget_session(business_id));
create policy service_areas_select_widget on public.service_areas for select
  using (app.is_widget_session(business_id));
create policy faqs_select_widget on public.faqs for select
  using (app.is_widget_session(business_id));
create policy business_hours_select_widget on public.business_hours for select
  using (app.is_widget_session(business_id));

create policy conversations_widget_select on public.conversations for select
  using (app.is_widget_session(business_id));
create policy conversations_widget_insert on public.conversations for insert
  with check (
    app.is_widget_session(business_id)
    and channel = 'widget'
    and status = 'open'
  );
create policy conversations_widget_update on public.conversations for update
  using (app.is_widget_session(business_id))
  with check (app.is_widget_session(business_id) and channel = 'widget');

create policy messages_widget_select on public.messages for select
  using (app.is_widget_session(business_id));
create policy messages_widget_insert on public.messages for insert
  with check (
    app.is_widget_session(business_id)
    and role::text in ('visitor', 'assistant')
    and source::text in ('visitor', 'assistant_demo', 'assistant_live')
  );
-- No UPDATE/DELETE policy for the widget: an exchange, once stored, is immutable from the
-- visitor side. Only a signed-in member of the business may change or remove it.

do $$
begin
  execute 'grant execute on function app.resolve_widget_business(text) to public';
exception when insufficient_privilege then
  raise notice 'skipping function grants';
end $$;
