-- 0010_widget_defaults_and_intent.sql
-- Two fixes, both found by hand rather than by the suite:
--
-- 1. WIDGET DEFAULTS WERE NEVER REACHED BY NEW TENANTS.
--    0009 backfilled widget_allowed_origins and widget_config with an UPDATE, which only
--    touches rows that already exist. Migrations run before the seed, so every seeded tenant
--    was inserted AFTERWARDS and fell back to the column DEFAULT: '{}' for the origins and
--    '{}' for the config. Consequences observed on a freshly seeded database:
--      * an empty origin allow-list, so only PUBLIC_WIDGET_ORIGIN was accepted and
--        `Origin: http://127.0.0.1:3100` was refused with origin_not_allowed;
--      * no widget config at all, so the widget-config endpoint had nothing honest to return.
--    The default is now set ON THE COLUMN, so any business created from here on inherits it,
--    and existing empty rows are backfilled once.
--
-- 2. Per-message intent. The engine already decides an intent for every reply; it was logged
--    but not stored, so the dashboard could not show what a visitor was actually asking about.
--    It is stored on the assistant message it belongs to (nullable: pre-0010 rows have none).

-- ---------------------------------------------------------------------------
-- 1. Origin allow-list default: BOTH loopback spellings for each local dev port
-- ---------------------------------------------------------------------------
-- A browser or curl may reach the dev server as either localhost or 127.0.0.1; the Origin
-- header carries whichever the user typed. Both must be accepted or the widget silently fails.
alter table public.businesses
  alter column widget_allowed_origins set default array[
    'https://cac99f77d1837c5aecc110a671dea4e3.ctonew.app',
    'http://localhost:3100',
    'http://127.0.0.1:3100',
    'http://localhost:3200',
    'http://127.0.0.1:3200'
  ];

update public.businesses
   set widget_allowed_origins = array[
         'https://cac99f77d1837c5aecc110a671dea4e3.ctonew.app',
         'http://localhost:3100',
         'http://127.0.0.1:3100',
         'http://localhost:3200',
         'http://127.0.0.1:3200'
       ]
 where cardinality(widget_allowed_origins) = 0;

-- ---------------------------------------------------------------------------
-- 2. Widget config default (generic; the seed writes the named, per-business version)
-- ---------------------------------------------------------------------------
-- The disclosure is mandatory and states the demo/live distinction explicitly, so a visitor
-- is never told a deterministic reply came from a live AI model.
alter table public.businesses
  alter column widget_config set default jsonb_build_object(
    'welcome_message',
      'Hi — I am the website assistant for this business. I answer only from information the business has approved.',
    'brand_color', '#0f172a',
    'assistant_disclosure',
      'You are chatting with an automated assistant, not a person. It answers only from information '
      || 'this business has approved. Replies marked "demo mode" are composed deterministically from '
      || 'those approved facts and are not generated by a live AI model. It cannot book, confirm or '
      || 'price work.',
    'response_mode', 'demo'
  );

update public.businesses
   set widget_config = jsonb_build_object(
         'welcome_message',
           'Hi — I am the website assistant for ' || name || '. I answer only from information this business has approved.',
         'brand_color', case industry::text
                          when 'veterinary' then '#0f766e'
                          when 'plumbing' then '#1d4ed8'
                          else '#0f172a'
                        end,
         'assistant_disclosure',
           'You are chatting with an automated assistant, not a person. It answers only from information '
           || name || ' has approved. Replies marked "demo mode" are composed deterministically from those '
           || 'approved facts and are not generated by a live AI model. It cannot book, confirm or price work.',
         'response_mode', ai_response_mode
       )
 where widget_config = '{}'::jsonb;

-- ---------------------------------------------------------------------------
-- 3. Intent on the assistant message
-- ---------------------------------------------------------------------------
alter table public.messages add column intent text;

alter table public.messages
  add constraint messages_intent_format
  check (intent is null or intent ~ '^[a-z_]{2,40}$');

comment on column public.messages.intent is
  'The deterministic engine intent behind an assistant reply (service_area, hours, pricing, emergency, ...). Null for visitor messages and for rows written before 0010.';
