/*!
 * ServiceFront embeddable chat widget (Phase 2b)
 * ---------------------------------------------------------------------------
 * Usage on any page:
 *
 *   <script src="https://<app-origin>/widget.js"
 *           data-widget-id="sfw_..."        (required, public id)
 *           data-api-base="https://<app-origin>"  (optional; defaults to this script's origin)
 *           data-title="Chat with us"        (optional)
 *           defer></script>
 *
 * Design rules, all deliberate:
 *   - CSS isolation: everything renders inside a shadow root, so the host page's CSS cannot
 *     reach the widget and the widget's CSS cannot reach the host page. No Tailwind classes,
 *     no global selectors, no injected document-level stylesheet.
 *   - Mobile first: the base layout is a full-screen sheet; the anchored desktop card is a
 *     min-width media query on top of it.
 *   - The business is identified ONLY by the public widget id. The widget never sends a
 *     business id, a role or a mode; the server derives the tenant from the URL.
 *   - Honesty: the effective answer mode comes from GET .../config, and the mode label is
 *     always on screen (header badge + footer) — before, during and after any message. A
 *     demo-mode reply is never presented as a live model answer.
 *   - Answers are rendered as text (textContent), never as HTML: reply, disclosure and source
 *     labels are data from the server.
 */
(function () {
  "use strict";

  if (window.__servicefrontWidget) return;
  window.__servicefrontWidget = true;

  var script = document.currentScript;
  if (!script) return;

  var WIDGET_ID_RE = /^sfw_[a-z0-9]{16,40}$/;
  var widgetId = (script.getAttribute("data-widget-id") || "").trim();
  if (!WIDGET_ID_RE.test(widgetId)) {
    console.warn("[ServiceFront] widget.js needs a valid data-widget-id (sfw_...).");
    return;
  }

  var apiBase = (script.getAttribute("data-api-base") || "").trim().replace(/\/+$/, "");
  if (!apiBase) {
    try {
      apiBase = new URL(script.src, document.baseURI).origin;
    } catch (err) {
      apiBase = window.location.origin;
    }
  }
  var title = (script.getAttribute("data-title") || "Chat with us").slice(0, 60);

  var MODE = {
    demo: {
      badge: "Demo mode",
      footer: "Demonstration mode — replies are composed deterministically from this business's approved facts, not generated by a live AI model.",
    },
    live: {
      badge: "Live AI",
      footer: "Live mode — replies are generated by the configured language model from this business's approved facts and checked for ungrounded claims.",
    },
  };

  var CSS = [
    ":host{all:initial}",
    "*,*::before,*::after{box-sizing:border-box}",
    ".sfw-root{font-family:system-ui,-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;",
    "font-size:15px;line-height:1.45;color:#0f172a;-webkit-font-smoothing:antialiased}",
    ".sfw-root button{font:inherit;color:inherit;cursor:pointer;border:0;background:none}",
    ".sfw-root p{margin:0}",
    ".sfw-launcher{position:fixed;right:16px;bottom:16px;z-index:2;pointer-events:auto;",
    "display:flex;align-items:center;gap:8px;min-height:52px;padding:0 18px;border-radius:999px;",
    "background:var(--sfw-brand,#1d4ed8);color:#fff;font-weight:600;box-shadow:0 10px 24px rgba(15,23,42,.28)}",
    ".sfw-launcher:focus-visible{outline:3px solid #0f172a;outline-offset:3px}",
    ".sfw-launcher svg{width:20px;height:20px;flex:none}",
    ".sfw-launcher[aria-expanded='true']{display:none}",
    ".sfw-panel{position:fixed;inset:0;z-index:3;pointer-events:auto;display:flex;flex-direction:column;",
    "background:#fff;box-shadow:0 -8px 32px rgba(15,23,42,.22)}",
    ".sfw-panel[hidden]{display:none}",
    ".sfw-head{display:flex;align-items:center;justify-content:space-between;gap:12px;padding:12px 14px;",
    "background:var(--sfw-brand,#1d4ed8);color:#fff}",
    ".sfw-head-text{display:flex;flex-direction:column;gap:2px;min-width:0}",
    ".sfw-title{font-weight:700;font-size:15px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}",
    ".sfw-badge{display:inline-block;align-self:flex-start;padding:1px 7px;border-radius:999px;",
    "background:rgba(255,255,255,.22);font-size:11px;font-weight:700;letter-spacing:.04em;text-transform:uppercase}",
    ".sfw-close{width:36px;height:36px;border-radius:999px;display:grid;place-items:center;font-size:22px;line-height:1;",
    "background:rgba(255,255,255,.16)}",
    ".sfw-close:focus-visible{outline:3px solid #fff;outline-offset:2px}",
    ".sfw-log{flex:1;overflow-y:auto;overscroll-behavior:contain;padding:14px;display:flex;flex-direction:column;gap:10px;",
    "background:#f8fafc}",
    ".sfw-msg{max-width:86%;padding:10px 12px;border-radius:14px;white-space:pre-wrap;word-break:break-word}",
    ".sfw-msg--bot{align-self:flex-start;background:#fff;border:1px solid #e2e8f0;border-bottom-left-radius:4px}",
    ".sfw-msg--user{align-self:flex-end;background:var(--sfw-brand,#1d4ed8);color:#fff;border-bottom-right-radius:4px}",
    ".sfw-msg--note{align-self:stretch;max-width:100%;background:#eef2f7;color:#334155;font-size:12.5px;line-height:1.4}",
    ".sfw-msg--error{align-self:stretch;max-width:100%;background:#fef2f2;border:1px solid #fecaca;color:#991b1b;font-size:13px}",
    ".sfw-meta{display:flex;flex-wrap:wrap;align-items:center;gap:6px;margin-top:8px;font-size:11.5px;color:#475569}",
    ".sfw-tag{padding:1px 6px;border-radius:999px;background:#e2e8f0;font-weight:600;text-transform:none}",
    ".sfw-sources{margin:6px 0 0;padding:0;list-style:none;display:flex;flex-direction:column;gap:2px;",
    "font-size:11.5px;color:#475569}",
    ".sfw-sources li::before{content:'↳ ';opacity:.6}",
    ".sfw-form{display:flex;gap:8px;padding:10px 12px;border-top:1px solid #e2e8f0;background:#fff}",
    ".sfw-input{flex:1;min-width:0;min-height:44px;padding:10px 12px;border:1px solid #cbd5e1;border-radius:10px;",
    "font:inherit;font-size:16px;color:#0f172a;background:#fff}",
    ".sfw-input:focus{outline:2px solid var(--sfw-brand,#1d4ed8);outline-offset:1px;border-color:transparent}",
    ".sfw-input:disabled{background:#f1f5f9;color:#64748b}",
    ".sfw-send{min-height:44px;padding:0 16px;border-radius:10px;background:var(--sfw-brand,#1d4ed8);color:#fff;font-weight:600}",
    ".sfw-send:disabled{opacity:.55;cursor:not-allowed}",
    ".sfw-send:focus-visible{outline:3px solid #0f172a;outline-offset:2px}",
    ".sfw-foot{padding:8px 14px 12px;background:#fff;border-top:1px solid #eef2f7;font-size:11.5px;color:#475569}",
    ".sfw-typing{color:#475569;font-style:italic}",
    "@media (min-width:560px){",
    ".sfw-launcher{right:24px;bottom:24px}",
    ".sfw-panel{inset:auto 24px 92px auto;width:380px;height:min(600px,calc(100vh - 140px));border-radius:16px;overflow:hidden;",
    "border:1px solid #e2e8f0}",
    ".sfw-head{border-radius:16px 16px 0 0}",
    "}",
    "@media (prefers-reduced-motion:no-preference){.sfw-panel{animation:sfw-in .18s ease-out}",
    "@keyframes sfw-in{from{opacity:0;transform:translateY(8px)}to{opacity:1;transform:none}}}",
  ].join("");

  function h(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined && text !== null) node.textContent = String(text);
    return node;
  }

  var host = document.createElement("div");
  host.setAttribute("data-servicefront-widget", widgetId);
  host.style.cssText = "position:fixed;inset:0;z-index:2147483000;pointer-events:none;";
  var shadow = host.attachShadow({ mode: "open" });
  var style = document.createElement("style");
  style.textContent = CSS;
  shadow.appendChild(style);

  var root = h("div", "sfw-root");

  var launcher = h("button", "sfw-launcher");
  launcher.type = "button";
  launcher.setAttribute("aria-expanded", "false");
  launcher.setAttribute("aria-label", "Open the chat assistant");
  launcher.innerHTML =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" ' +
    'stroke-linejoin="round" aria-hidden="true"><path d="M21 11.5a8.4 8.4 0 0 1-8.5 8.5 8.6 8.6 0 0 1-3.9-.9L3 21l1.9-5.1a8.6 8.6 0 0 1-.9-3.9A8.4 8.4 0 0 1 12.5 3 8.4 8.4 0 0 1 21 11.5Z"/></svg>';
  launcher.appendChild(h("span", null, "Chat"));

  var panel = h("section", "sfw-panel");
  panel.hidden = true;
  panel.setAttribute("role", "dialog");
  panel.setAttribute("aria-modal", "false");
  panel.setAttribute("aria-label", title + " — automated assistant");

  var head = h("div", "sfw-head");
  var headText = h("div", "sfw-head-text");
  headText.appendChild(h("span", "sfw-title", title));
  var modeBadge = h("span", "sfw-badge", MODE.demo.badge);
  headText.appendChild(modeBadge);
  var closeBtn = h("button", "sfw-close", "\u00d7");
  closeBtn.type = "button";
  closeBtn.setAttribute("aria-label", "Close chat");
  head.appendChild(headText);
  head.appendChild(closeBtn);

  var log = h("div", "sfw-log");
  log.setAttribute("role", "log");
  log.setAttribute("aria-live", "polite");
  log.setAttribute("aria-label", "Conversation");

  var form = h("form", "sfw-form");
  var input = h("input", "sfw-input");
  input.type = "text";
  input.maxLength = 1000;
  input.autocomplete = "off";
  input.placeholder = "Ask a question\u2026";
  input.setAttribute("aria-label", "Your message");
  var send = h("button", "sfw-send", "Send");
  send.type = "submit";
  form.appendChild(input);
  form.appendChild(send);

  var foot = h("p", "sfw-foot", MODE.demo.footer);

  panel.appendChild(head);
  panel.appendChild(log);
  panel.appendChild(form);
  panel.appendChild(foot);
  root.appendChild(launcher);
  root.appendChild(panel);
  shadow.appendChild(root);

  var state = {
    config: null,
    loading: false,
    failed: false,
    conversationId: null,
    busy: false,
    mode: "demo",
  };

  function applyMode(mode) {
    state.mode = mode === "live" ? "live" : "demo";
    var copy = MODE[state.mode];
    modeBadge.textContent = copy.badge;
    foot.textContent = copy.footer;
  }

  function scrollToEnd() {
    log.scrollTop = log.scrollHeight;
  }

  function addMessage(kind, text) {
    var node = h("div", "sfw-msg sfw-msg--" + kind, text);
    log.appendChild(node);
    scrollToEnd();
    return node;
  }

  function addAssistantMessage(payload) {
    var bubble = addMessage("bot", payload.reply);
    var meta = h("div", "sfw-meta");
    var tag = h("span", "sfw-tag", payload.modeLabel || MODE[payload.mode === "live" ? "live" : "demo"].badge);
    meta.appendChild(tag);
    if (payload.answeredFromKnowledge === false) meta.appendChild(h("span", null, "not confirmed in approved facts"));
    bubble.appendChild(meta);

    var sources = Array.isArray(payload.sources) ? payload.sources : [];
    if (sources.length) {
      var list = h("ul", "sfw-sources");
      for (var i = 0; i < sources.length; i++) {
        var source = sources[i] || {};
        var label = typeof source.label === "string" && source.label ? source.label : String(source.type || "fact");
        list.appendChild(h("li", null, label));
      }
      bubble.appendChild(list);
    }
    scrollToEnd();
    return bubble;
  }

  function setBusy(busy) {
    state.busy = busy;
    input.disabled = busy;
    send.disabled = busy;
    panel.setAttribute("aria-busy", busy ? "true" : "false");
  }

  function loadConfig() {
    if (state.config || state.loading) return Promise.resolve(state.config);
    state.loading = true;
    var note = addMessage("note", "Connecting to the assistant\u2026");
    return fetch(apiBase + "/api/widget/" + encodeURIComponent(widgetId) + "/config", {
      method: "GET",
      headers: { accept: "application/json" },
      mode: "cors",
      credentials: "omit",
    })
      .then(function (res) {
        return res.json().then(function (body) {
          if (!res.ok) throw new Error((body && body.error && body.error.message) || "This assistant is not available.");
          return body;
        });
      })
      .then(function (config) {
        state.config = config;
        state.failed = false;
        note.remove();
        applyMode(config.responseMode);
        if (config.brandColor && /^#[0-9a-f]{3,8}$/i.test(config.brandColor)) {
          root.style.setProperty("--sfw-brand", config.brandColor);
        }
        addMessage("bot", config.welcomeMessage || "Hi \u2014 ask me anything about this business.");
        if (config.assistantDisclosure) addMessage("note", config.assistantDisclosure);
        input.focus();
        return config;
      })
      .catch(function (err) {
        state.failed = true;
        note.remove();
        addMessage("error", (err && err.message) || "The assistant is unavailable right now. Please try again shortly.");
        return null;
      })
      .then(function (config) {
        state.loading = false;
        return config;
      });
  }

  function open() {
    panel.hidden = false;
    launcher.setAttribute("aria-expanded", "true");
    if (state.config || state.failed) {
      input.focus();
    } else {
      loadConfig();
    }
  }

  function close() {
    panel.hidden = true;
    launcher.setAttribute("aria-expanded", "false");
    launcher.focus();
  }

  function sendMessage(text) {
    var trimmed = text.trim();
    if (!trimmed || state.busy) return;
    addMessage("user", trimmed);
    input.value = "";
    setBusy(true);

    var typing = h("div", "sfw-msg sfw-msg--bot sfw-typing", "Thinking\u2026");
    log.appendChild(typing);
    scrollToEnd();

    var payload = { text: trimmed };
    if (state.conversationId) payload.conversationId = state.conversationId;

    fetch(apiBase + "/api/widget/" + encodeURIComponent(widgetId) + "/message", {
      method: "POST",
      headers: { "content-type": "application/json", accept: "application/json" },
      mode: "cors",
      credentials: "omit",
      body: JSON.stringify(payload),
    })
      .then(function (res) {
        return res.json().then(function (body) {
          return { res: res, body: body };
        });
      })
      .then(function (out) {
        typing.remove();
        if (!out.res.ok) {
          var message = (out.body && out.body.error && out.body.error.message) || "The assistant is unavailable right now.";
          addMessage("error", message);
          return;
        }
        if (out.body && out.body.conversationId) state.conversationId = out.body.conversationId;
        applyMode(out.body && out.body.mode);
        addAssistantMessage(out.body || {});
      })
      .catch(function () {
        typing.remove();
        addMessage("error", "The message did not reach the assistant. Check the connection and try again.");
      })
      .then(function () {
        setBusy(false);
        input.focus();
      });
  }

  launcher.addEventListener("click", open);
  closeBtn.addEventListener("click", close);
  form.addEventListener("submit", function (event) {
    event.preventDefault();
    sendMessage(input.value);
  });
  panel.addEventListener("keydown", function (event) {
    if (event.key === "Escape") close();
  });

  function mount() {
    document.body.appendChild(host);
  }

  if (document.body) mount();
  else document.addEventListener("DOMContentLoaded", mount);
})();
